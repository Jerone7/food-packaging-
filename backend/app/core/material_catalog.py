class MaterialCatalogService:
    """Provides querying, filtering, radar scoring, and indexing across the packaging material catalog."""

    def __init__(self):
        self._custom_materials: List[MaterialSpecification] = []

    def get_all_materials(self) -> List[MaterialSpecification]:
        return list(self._custom_materials) + list(PACKAGING_CATALOG)

    def get_by_id(self, material_id: str) -> Optional[MaterialSpecification]:
        for mat in self.get_all_materials():
            if mat.material_id == material_id:
                return mat
        return None

    def get_material_by_id(self, material_id: str) -> Optional[MaterialSpecification]:
        return self.get_by_id(material_id)

    def get_by_polymer_family(self, family: str) -> List[MaterialSpecification]:
        return [m for m in self.get_all_materials() if m.polymer_family == family]

    def filter_by_temperature(self, temp_c: float) -> List[MaterialSpecification]:
        return [m for m in self.get_all_materials() if m.temp_min_c <= temp_c <= m.temp_max_c]

    def add_custom_material(self, mat: MaterialSpecification) -> MaterialSpecification:
        # Remove if exists with same ID
        self._custom_materials = [m for m in self._custom_materials if m.material_id != mat.material_id]
        self._custom_materials.insert(0, mat)
        return mat

    def calculate_radar_scores(self, mat: MaterialSpecification) -> MaterialPropertyRadarSchema:
        """Calculates normalized 0-100 radar scores for 6 key decision axes."""
        # 1. Barrier Score: Lower OTR & WVTR yields higher barrier score
        if mat.is_breathable:
            barrier_score = 45.0  # Breathable EMAP is engineered for high permeation
        else:
            otr_term = max(0.0, 100.0 - (mat.otr_cc_m2_day * 2.0))
            wvtr_term = max(0.0, 100.0 - (mat.wvtr_g_m2_day * 4.0))
            barrier_score = (0.55 * otr_term) + (0.45 * wvtr_term)

        # 2. Mechanical Strength Score
        tensile_norm = min(100.0, (mat.tensile_strength_mpa / 150.0) * 100.0)
        puncture_norm = min(100.0, (mat.puncture_resistance_n / 100.0) * 100.0)
        mechanical_score = (0.5 * tensile_norm) + (0.5 * puncture_norm)

        # 3. Sustainability Score
        sustainability_score = mat.sustainability_score

        # 4. Thermal Score: Range span and extremes
        temp_span = mat.temp_max_c - mat.temp_min_c
        thermal_score = min(100.0, max(20.0, (temp_span / 160.0) * 100.0))
        if mat.is_retort_grade or mat.is_cryogenic_grade:
            thermal_score = min(100.0, thermal_score + 15.0)

        # 5. Cost Efficiency Score: Lower unit cost yields higher efficiency score
        cost_efficiency_score = max(10.0, min(100.0, 100.0 - (mat.estimated_unit_cost_inr * 9.0)))

        # 6. Optical Score: Clarity or Light Shield
        if mat.uv_transmittance_pct <= 2.0:
            optical_score = 95.0  # Total light shield protection
        elif "clear" in mat.optical_clarity.lower():
            optical_score = 90.0  # High clarity
        else:
            optical_score = 65.0

        return MaterialPropertyRadarSchema(
            barrier_score=round(max(5.0, min(100.0, barrier_score)), 1),
            mechanical_score=round(max(5.0, min(100.0, mechanical_score)), 1),
            sustainability_score=round(max(0.0, min(100.0, sustainability_score)), 1),
            thermal_score=round(max(5.0, min(100.0, thermal_score)), 1),
            cost_efficiency_score=round(max(5.0, min(100.0, cost_efficiency_score)), 1),
            optical_score=round(max(5.0, min(100.0, optical_score)), 1),
        )

    def to_detail_response(self, mat: MaterialSpecification, db_id: Optional[int] = None) -> PackagingMaterialDetailResponse:
        """Converts MaterialSpecification to full Pydantic PackagingMaterialDetailResponse."""
        # Derive barrier tier
        if mat.otr_cc_m2_day <= 0.05 and mat.wvtr_g_m2_day <= 0.05:
            barrier_tier = "Hermetic Zero-Permeation"
        elif mat.is_breathable:
            barrier_tier = "Breathable EMAP"
        elif mat.otr_cc_m2_day <= 1.5:
            barrier_tier = "Ultra-High Barrier"
        elif mat.otr_cc_m2_day <= 35.0:
            barrier_tier = "High Barrier"
        else:
            barrier_tier = "Moderate Barrier"

        radar = self.calculate_radar_scores(mat)

        return PackagingMaterialDetailResponse(
            id=db_id,
            material_id=mat.material_id,
            name=mat.name,
            category=mat.category,
            polymer_family=mat.polymer_family,
            structure=mat.structure,
            form_factor=mat.form_factor,
            barrier_profile=BarrierProfileDetailSchema(
                otr_cc_m2_day=mat.otr_cc_m2_day,
                wvtr_g_m2_day=mat.wvtr_g_m2_day,
                co2_permeability=mat.co2_permeability,
                selectivity_beta=mat.selectivity_beta,
                thickness_microns=mat.thickness_microns,
                barrier_tier=barrier_tier,
                gas_flush_compatible=mat.gas_flush_compatible,
            ),
            mechanical_profile=MechanicalProfileSchema(
                tensile_strength_mpa=mat.tensile_strength_mpa,
                puncture_resistance_n=mat.puncture_resistance_n,
                elongation_pct=mat.elongation_pct,
                form_factor=mat.form_factor,
                durability_rating="High" if mat.puncture_resistance_n >= 40.0 else "Moderate",
            ),
            thermal_profile=ThermalProfileSchema(
                temp_min_c=mat.temp_min_c,
                temp_max_c=mat.temp_max_c,
                thermal_class=mat.thermal_class,
                is_cryogenic_grade=mat.is_cryogenic_grade,
                is_retort_grade=mat.is_retort_grade,
            ),
            optical_profile=OpticalProfileSchema(
                uv_transmittance_pct=mat.uv_transmittance_pct,
                optical_clarity=mat.optical_clarity,
                light_barrier_rating="Total Block" if mat.uv_transmittance_pct <= 1.0 else ("High Shield" if mat.uv_transmittance_pct <= 15.0 else "Clear"),
            ),
            environmental_profile=EnvironmentalProfileSchema(
                sustainability_score=mat.sustainability_score,
                recyclability_score=mat.recyclability_score,
                biodegradability_score=mat.biodegradability_score,
                is_biodegradable=mat.is_biodegradable,
                is_recyclable=mat.is_recyclable,
                resin_code=mat.resin_code,
                composting_standard=mat.composting_standard,
            ),
            economic_profile=EconomicProfileSchema(
                cost_category=mat.cost_category,
                estimated_unit_cost_inr=mat.estimated_unit_cost_inr,
                market_scalability="High" if mat.sustainability_score < 90 else "Growing Commercial",
            ),
            functional_flags={
                "is_breathable": mat.is_breathable,
                "is_biodegradable": mat.is_biodegradable,
                "is_recyclable": mat.is_recyclable,
                "is_retort_grade": mat.is_retort_grade,
                "is_cryogenic_grade": mat.is_cryogenic_grade,
                "gas_flush_compatible": mat.gas_flush_compatible,
            },
            recommended_applications=mat.recommended_applications,
            regulatory_certifications=mat.regulatory_certifications or ["FDA 21 CFR 177", "FSSAI IS 9845"],
            radar_scores=radar,
            notes=mat.notes,
            is_active_entry=mat.is_active_entry,
        )

    def filter_materials(
        self,
        search: Optional[str] = None,
        category: Optional[str] = None,
        polymer_family: Optional[str] = None,
        max_otr: Optional[float] = None,
        max_wvtr: Optional[float] = None,
        min_sustainability: Optional[float] = None,
        is_biodegradable: Optional[bool] = None,
        is_recyclable: Optional[bool] = None,
        is_cryogenic: Optional[bool] = None,
        is_retort: Optional[bool] = None,
        cost_tier: Optional[str] = None,
        sort_by: Optional[str] = "sustainability_score",
        sort_order: Optional[str] = "desc",
        limit: int = 50,
        offset: int = 0,
    ) -> List[PackagingMaterialDetailResponse]:
        """Filters catalog materials by multi-parameter criteria with sorting and pagination."""
        materials = self.get_all_materials()

        if search:
            q = search.lower()
            materials = [
                m for m in materials
                if q in m.name.lower() or q in m.category.lower() or q in m.structure.lower() or any(q in app.lower() for app in m.recommended_applications)
            ]

        if category:
            materials = [m for m in materials if category.lower() in m.category.lower()]

        if polymer_family:
            materials = [m for m in materials if polymer_family.lower() in m.polymer_family.lower()]

        if max_otr is not None:
            materials = [m for m in materials if m.otr_cc_m2_day <= max_otr]

        if max_wvtr is not None:
            materials = [m for m in materials if m.wvtr_g_m2_day <= max_wvtr]

        if min_sustainability is not None:
            materials = [m for m in materials if m.sustainability_score >= min_sustainability]

        if is_biodegradable is not None:
            materials = [m for m in materials if m.is_biodegradable == is_biodegradable]

        if is_recyclable is not None:
            materials = [m for m in materials if m.is_recyclable == is_recyclable]

        if is_cryogenic is not None:
            materials = [m for m in materials if (m.is_cryogenic_grade or m.temp_min_c <= -25.0) == is_cryogenic]

        if is_retort is not None:
            materials = [m for m in materials if m.is_retort_grade == is_retort]

        if cost_tier:
            materials = [m for m in materials if cost_tier.lower() in m.cost_category.lower()]

        # Sorting
        reverse = (sort_order or "desc").lower() == "desc"
        if sort_by == "otr":
            materials.sort(key=lambda m: m.otr_cc_m2_day, reverse=reverse)
        elif sort_by == "wvtr":
            materials.sort(key=lambda m: m.wvtr_g_m2_day, reverse=reverse)
        elif sort_by == "cost" or sort_by == "estimated_unit_cost_inr":
            materials.sort(key=lambda m: m.estimated_unit_cost_inr, reverse=reverse)
        elif sort_by == "tensile" or sort_by == "tensile_strength_mpa":
            materials.sort(key=lambda m: m.tensile_strength_mpa, reverse=reverse)
        elif sort_by == "name":
            materials.sort(key=lambda m: m.name.lower(), reverse=reverse)
        else:  # default sustainability_score
            materials.sort(key=lambda m: m.sustainability_score, reverse=reverse)

        paginated = materials[offset : offset + limit]
        return [self.to_detail_response(m) for m in paginated]

    def get_category_summaries(self) -> List[MaterialCategorySummaryResponse]:
        """Returns grouped category statistics and sample materials."""
        materials = self.get_all_materials()
        groups: Dict[str, List[MaterialSpecification]] = {}
        for m in materials:
            groups.setdefault(m.category, []).append(m)

        summaries = []
        for cat_name, items in groups.items():
            avg_eco = sum(i.sustainability_score for i in items) / len(items)
            summaries.append(
                MaterialCategorySummaryResponse(
                    category=cat_name,
                    count=len(items),
                    sample_materials=[i.name for i in items[:4]],
                    average_sustainability=round(avg_eco, 1),
                    description=f"Collection of {len(items)} {cat_name.lower()} options with avg sustainability of {avg_eco:.0f}/100.",
                )
            )

        summaries.sort(key=lambda s: s.count, reverse=True)
        return summaries


