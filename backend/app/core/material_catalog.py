@dataclass
class MaterialSpecification:
    material_id: str
    name: str
    category: str  # e.g., "Biodegradable Bio-Polymer", "Conventional Polymer", "High-Barrier Laminate"
    polymer_family: str  # Matches ML classifier classes
    structure: str
    thickness_microns: float
    otr_cc_m2_day: float  # Oxygen Transmission Rate at 23°C, 0% RH
    wvtr_g_m2_day: float  # Water Vapor Transmission Rate at 38°C, 90% RH
    tensile_strength_mpa: float
    puncture_resistance_n: float
    sustainability_score: float  # 0 to 100
    estimated_unit_cost_inr: float  # Standard unit cost in INR
    temp_min_c: float
    temp_max_c: float
    is_breathable: bool
    is_biodegradable: bool
    is_recyclable: bool
    is_retort_grade: bool
    is_cryogenic_grade: bool
    gas_flush_compatible: bool
    recommended_applications: List[str]
    notes: str
    # Extended 12-Property Vectors
    form_factor: str = "Flexible Pouch"
    co2_permeability: Optional[float] = None
    selectivity_beta: Optional[float] = None
    elongation_pct: float = 100.0
    uv_transmittance_pct: float = 20.0
    optical_clarity: str = "Translucent"
    thermal_class: str = "Ambient / Refrigerated"
    recyclability_score: float = 0.0
    biodegradability_score: float = 0.0
    resin_code: str = "OTHER_7"
