    regulatory_certifications: List[str] = field(default_factory=lambda: ["FDA 21 CFR 177.1520", "FSSAI IS 9845"])
    is_active_entry: bool = True

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


