"""
Pydantic v2 Schemas for Module 11: Sustainability Analysis.
Provides strict type definitions, enums, empirical LCA indicators,
packaging waste potential schemas, and multi-material comparison models.
"""

from typing import List, Optional, Dict, Any
from enum import Enum
from pydantic import BaseModel, Field, ConfigDict


class RecyclabilityTier(str, Enum):
    HIGH = "High"
    MEDIUM = "Medium"
    LOW = "Low"
    NON_RECYCLABLE = "Non-Recyclable"


class BiodegradabilityTier(str, Enum):
    HIGH = "High"
    MEDIUM = "Medium"
    LOW = "Low"
    NON_BIODEGRADABLE = "Non-Biodegradable"


class ReusabilityTier(str, Enum):
    HIGH = "High"
    MEDIUM = "Medium"
    LOW = "Low"
    SINGLE_USE = "Single-Use"


class WastePotentialLevel(str, Enum):
    VERY_LOW = "Very Low"
    LOW = "Low"
    MODERATE = "Moderate"
    HIGH = "High"
    VERY_HIGH = "Very High"


class SustainabilityEvaluateRequest(BaseModel):
    """Input payload for dynamic parametric sustainability & LCA evaluation."""
    model_config = ConfigDict(extra="ignore")

    material_id: str = Field(..., description="Unique identifier of the packaging material")
    material_name: Optional[str] = Field(None, description="Human-readable material name")
    package_type: str = Field("Stand-up Doypack (Bottom Gusset)", description="Packaging form factor")
    unit_mass_grams: Optional[float] = Field(None, ge=0.01, description="Calculated or manual unit mass in grams")
    length_cm: float = Field(18.0, gt=0.0, description="Package length in cm")
    width_cm: float = Field(12.0, gt=0.0, description="Package width in cm")
    depth_or_gusset_cm: float = Field(4.0, ge=0.0, description="Package depth or gusset width in cm")
    thickness_microns: float = Field(50.0, gt=0.0, description="Total film gauge or substrate thickness in microns")
    batch_size_units: int = Field(10000, ge=100, le=10000000, description="Production batch volume in units")
    pcr_percentage: float = Field(0.0, ge=0.0, le=100.0, description="Post-Consumer Recycled content percentage (0-100%)")
    food_commodity_id: Optional[str] = Field(None, description="Optional food commodity context")


class EnvironmentalIndicatorSchema(BaseModel):
    """Empirical Life Cycle Assessment (LCA) environmental indicators."""
    model_config = ConfigDict(extra="ignore")

    carbon_footprint_kg_co2e_per_unit: float = Field(..., description="Embodied carbon per individual package unit in kg CO2e")
    carbon_footprint_kg_co2e_total_batch: float = Field(..., description="Total carbon footprint for the entire production batch in kg CO2e")
    water_footprint_liters_per_unit: float = Field(..., description="Freshwater consumption per unit in Liters")
    water_footprint_liters_total_batch: float = Field(..., description="Total freshwater consumption for the production batch in Liters")
    pcr_carbon_reduction_pct: float = Field(..., description="Carbon emission abatement percentage due to PCR content")
    embodied_energy_mj_per_kg: float = Field(..., description="Primary energy demand (PED) in MJ per kg of substrate")


class PackagingWasteSchema(BaseModel):
    """Packaging waste potential and circularity metrics."""
    model_config = ConfigDict(extra="ignore")

    unit_waste_grams: float = Field(..., description="Solid waste generated per package unit in grams")
    total_batch_waste_kg: float = Field(..., description="Total solid waste generated by the batch in kg")
    waste_potential_level: WastePotentialLevel = Field(..., description="Categorical waste severity level")
    landfill_burden_kg: float = Field(..., description="Estimated mass of packaging ending in landfill in kg")
    diversion_potential_pct: float = Field(..., description="Estimated end-of-life landfill diversion percentage (0-100%)")
    circularity_index: float = Field(..., ge=0.0, le=1.0, description="Ellen MacArthur Foundation Material Circularity Indicator (0.0 - 1.0)")
    primary_disposal_pathway: str = Field(..., description="Recommended primary end-of-life pathway")


class SustainabilityProfileResponse(BaseModel):
    """Master response schema for verified packaging sustainability profile."""
    model_config = ConfigDict(extra="ignore")

    material_id: str = Field(..., description="Unique material ID")
    material_name: str = Field(..., description="Commercial/chemical material name")
    category: str = Field(..., description="Material classification category")
    polymer_family: str = Field(..., description="Polymer or substrate family")
    resin_identification_code: str = Field(..., description="Resin Identification Code (RIC 1-7 or PAP)")
    
    # Core 3 Pillars Display
    recyclability: RecyclabilityTier = Field(..., description="Recyclability level")
    recyclability_notes: str = Field(..., description="Municipal sorting and recycling infrastructure details")
    biodegradability: BiodegradabilityTier = Field(..., description="Biodegradability classification")
    biodegradability_standard: Optional[str] = Field(None, description="Certified standard (e.g. EN 13432, ASTM D6400, NF T 51-800)")
    biodegradability_notes: str = Field(..., description="Composting conditions and marine/soil persistence notes")
    reusability: ReusabilityTier = Field(..., description="Reusability classification")
    reusability_cycles: int = Field(..., ge=1, description="Estimated multi-trip wash and reuse cycle capacity")
    
    # Material Type & Feedstock Origin
    material_type_description: str = Field(..., description="Detailed description of polymer and feedstock origin")
    pcr_content_pct: float = Field(0.0, description="Post-Consumer Recycled percentage applied")
    bio_based_content_pct: float = Field(0.0, description="Bio-based renewable carbon content percentage")
    
    # Environmental Considerations & Certifications
    environmental_considerations: List[str] = Field(default_factory=list, description="Specific eco warnings, microplastics, and guidance")
    regulatory_certifications: List[str] = Field(default_factory=list, description="Food-contact and compostability certifications")
    
    # Calculated Environmental & Waste Metrics
    environmental_indicators: EnvironmentalIndicatorSchema = Field(..., description="Empirical LCA carbon and water metrics")
    waste_potential: PackagingWasteSchema = Field(..., description="Solid waste and circularity metrics")
    
    # Provenance & Verification
    verified_data_source: str = Field(..., description="Primary peer-reviewed citation or LCA database")
    source_doi_or_standard: str = Field(..., description="DOI link, standard number, or database reference")
    is_empirical_verified: bool = Field(True, description="Strict provenance flag confirming empirical verified baseline")


class SustainabilityCompareRequest(BaseModel):
    """Payload to compare sustainability profiles of up to 4 materials side-by-side."""
    model_config = ConfigDict(extra="ignore")

    material_ids: List[str] = Field(..., min_length=2, max_length=4, description="List of 2 to 4 material IDs to compare")
    package_type: str = Field("Stand-up Doypack (Bottom Gusset)", description="Form factor for comparative evaluation")
    length_cm: float = Field(18.0, gt=0.0)
    width_cm: float = Field(12.0, gt=0.0)
    depth_or_gusset_cm: float = Field(4.0, ge=0.0)
    thickness_microns: float = Field(50.0, gt=0.0)
    batch_size_units: int = Field(10000, ge=100, le=10000000)


class SustainabilityCompareResponse(BaseModel):
    """Response containing comparative sustainability evaluation across multiple materials."""
    model_config = ConfigDict(extra="ignore")

    materials: List[SustainabilityProfileResponse] = Field(..., description="List of evaluated sustainability profiles")
    best_recyclability_material_id: str = Field(..., description="Material ID with highest recyclability score")
    lowest_carbon_material_id: str = Field(..., description="Material ID with lowest total batch carbon footprint")
    lowest_waste_material_id: str = Field(..., description="Material ID with lowest total solid waste burden")
    eco_tradeoff_summary: str = Field(..., description="Synthesized trade-off analysis explaining environmental pros and cons")
